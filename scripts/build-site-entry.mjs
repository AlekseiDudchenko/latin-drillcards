import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

// V2 is the only site entry. A hosted build must configure its v2 backend.
const MARKER = '# Generated by scripts/build-site-entry.mjs';
const V2_HOME = '/v2/today';
const LEGAL_PATHS = ['privacy', 'terms'];

/** The entry and, for v2, the host redirects (Cloudflare Pages `_redirects`; 302 so a rollback is not cached). */
export function siteEntry(env, environment) {
  const entry = env.DRILLCARDS_SITE_ENTRY || 'v2';
  if (entry !== 'v2') throw new Error('V1 is retired; DRILLCARDS_SITE_ENTRY must be v2');
  const localPreview = !environment?.configured && environment?.environment === 'local' && !env.DRILLCARDS_SITE_ENTRY && !env.CF_PAGES;
  if (localPreview) return { entry, redirects: null };
  // A v2 entry without a backend would silently turn every visitor into a local-only guest.
  if (!environment?.configured) throw new Error('DRILLCARDS_SITE_ENTRY=v2 needs a configured v2 environment (the V2_* variables)');
  if (environment.environment === 'local') throw new Error('DRILLCARDS_SITE_ENTRY=v2 is for a hosted environment, not local');
  const redirects = [MARKER + ' (DRILLCARDS_SITE_ENTRY=v2): the v2 home is the site entry.',
    // v1 routes have no v2 equivalent URL; they all start on the v2 home.
    ...['/', '/index.html', '/de', '/de/*'].map(from => `${from.padEnd(12)} ${V2_HOME}  302`),
    // Except the legal pages: /privacy is the v1 policy URL that the Google sign-in consent screen and old links still name.
    ...LEGAL_PATHS.map(name => `${`/${name}`.padEnd(12)} /v2/${name}  302`)].join('\n') + '\n';
  return { entry, redirects };
}

const NOINDEX = '<meta name="robots" content="noindex">';
/** The site entry must be indexable: with v2 as the entry the root redirects to the v2 home, so its
 * preview-time noindex would drop the site from search. The other v2 pages keep theirs. */
export function indexableHome(html, entry) {
  return entry === 'v2' ? html.replace(NOINDEX, '') : html; // idempotent: a rebuild in the same tree is a no-op
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const environment = JSON.parse(readFileSync('public/v2/environment.json', 'utf8'));
  const { entry, redirects } = siteEntry(process.env, environment);
  const target = 'public/_redirects';
  if (redirects) writeFileSync(target, redirects);
  // Remove only a file this script wrote; never a hand-written one.
  else if (existsSync(target) && readFileSync(target, 'utf8').startsWith(MARKER)) rmSync(target);
  // Hand-written and tracked like sw.js: rewritten only in a v2-entry build.
  if (redirects) writeFileSync('public/v2/today.html', indexableHome(readFileSync('public/v2/today.html', 'utf8'), entry));
  console.log(`Site entry: ${entry}${redirects ? ` (/ and /de/* → ${V2_HOME})` : ''}`);
}
